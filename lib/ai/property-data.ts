export function searchProperties(filters: SearchFilters = {}): Property[] {
  return PROPERTIES.filter((property) => {
    if (filters.type && property.type !== filters.type) {
      return false;
    }
    if (filters.minPrice !== undefined && property.price < filters.minPrice) {
      return false;
    }
    if (filters.maxPrice !== undefined && property.price > filters.maxPrice) {
      return false;
    }
    if (filters.bedrooms !== undefined && property.bedrooms !== filters.bedrooms) {
      return false;
    }
    if (filters.location) {
      const loc = filters.location.trim().toLowerCase();
      const matchLoc = property.location.toLowerCase().includes(loc);
      const matchCity = property.city.toLowerCase().includes(loc);
      if (!matchLoc && !matchCity) {
        return false;
      }
    }
    if (filters.city) {
      const city = filters.city.trim().toLowerCase();
      if (!property.city.toLowerCase().includes(city)) {
        return false;
      }
    }
    return true;
  });
}

export function getPropertyById(id: string): Property | undefined {
  return PROPERTIES.find((property) => property.id.toLowerCase() === id.trim().toLowerCase());
}
